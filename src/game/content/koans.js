// rng: () => [0,1). pool: array of strings. avoidLast: string to avoid repeating immediately.
export function pickKoan(rng, pool, avoidLast) {
  if (!pool || !pool.length) return '';
  if (pool.length === 1) return pool[0];
  let i = Math.floor(rng() * pool.length) % pool.length;
  if (avoidLast !== undefined && pool[i] === avoidLast) i = (i + 1) % pool.length;
  return pool[i];
}
